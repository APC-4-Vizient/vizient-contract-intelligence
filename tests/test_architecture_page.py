"""The 3D architecture view of the Contract Review app, and docs/architecture-3d.html, the standalone page built from it.

The view states numbers and lists (tables, columns, flow actions, size limits, the checklist, the statuses). Each one is
checked against the file it describes, because a count written into a diagram goes stale without anyone noticing.

The page is generated by `npm run build:standalone` in contract-review/. It records every source it was built from with
that file's hash, so it fails here while any of them has changed, and it must stay one self-contained file: nothing to
fetch and no host named.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

import flowlib  # noqa: E402
import schemalib  # noqa: E402

APP = ROOT / "contract-review"
PAGE = ROOT / "docs" / "architecture-3d.html"
ARCHITECTURE = (APP / "src" / "about" / "architecture.ts").read_text(encoding="utf-8")
HOW_IT_WORKS = (APP / "src" / "about" / "howItWorksCopy.ts").read_text(encoding="utf-8")
FUNCTION_ROUTES = (ROOT / "function" / "routes.py").read_text(encoding="utf-8")

NUMBER_WORDS = {word: number for number, word in enumerate(
    "zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen "
    "eighteen nineteen twenty".split())}
BUILD_COMMAND = "Run `npm run build:standalone` in contract-review/ and commit docs/architecture-3d.html."


# ---- what the view says -------------------------------------------------------------------------------------------

def stated(pattern: str, text: str = ARCHITECTURE) -> list[int]:
    """Every number that the text (architecture.ts unless another is given) writes where the pattern's one group is, as digits or as a word."""
    found = [int(number) if number.isdigit() else NUMBER_WORDS[number.lower()] for number in re.findall(pattern, text)]
    assert found, f"{pattern!r} no longer matches: if the wording changed, change this test with it"
    return found


def action_count(actions: dict[str, Any] | None) -> int:
    """Every action in a flow definition, nested ones included."""
    total = 0
    for action in (actions or {}).values():
        total += 1 + action_count(action.get("actions")) + action_count((action.get("else") or {}).get("actions"))
        for case in (action.get("cases") or {}).values():
            total += action_count(case.get("actions"))
        total += action_count((action.get("default") or {}).get("actions"))
    return total


@pytest.fixture(scope="module")
def schema() -> dict[str, Any]:
    return schemalib.load_schema()


def test_the_tables_and_columns_it_names_are_the_schemas(schema: dict[str, Any]) -> None:
    columns = sum(len(schemalib.column_names(schema, table)) for table in schema["tables"])
    assert stated(r"kicker: '(\d+) tables'") == [len(schema["tables"])]
    assert stated(r"\b(One|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten) tables:") == [len(schema["tables"])]
    assert stated(r"\((\d+) columns in all\)") == [columns]


def test_the_flow_action_counts_are_the_flows(schema: dict[str, Any]) -> None:
    counts = {spec.name: action_count(spec.definition["actions"]) for spec in flowlib.flow_specs(schema)}
    assert stated(r"'(\d+) actions\. Setting the status") == [counts[flowlib.INTAKE_FLOW]]
    assert stated(r"The Intake flow has (\d+) actions") == [counts[flowlib.INTAKE_FLOW]]
    assert stated(r"'(\d+) actions with Try and Catch") == [counts[flowlib.ANALYSIS_FLOW]]
    assert stated(r"The Analysis flow has (\d+) actions") == [counts[flowlib.ANALYSIS_FLOW]]


def test_the_checklist_size_is_the_number_of_questions_the_ai_answers() -> None:
    items = json.loads((ROOT / "checklist" / "checklist.json").read_text(encoding="utf-8-sig"))["items"]
    answered = sum(1 for item in items if item["source"] == "analyzer")
    assert stated(r"(\d+)-item checklist") == [answered] * len(stated(r"(\d+)-item checklist"))
    assert stated(r"'(\d+) answers with proof'") == [answered]
    assert stated(r"\b(Twenty) answers") == [answered]


def test_the_size_limits_are_the_codes() -> None:
    function_limit = re.search(r"^MAX_PDF_BYTES = (\d+) \* 1024 \* 1024$", FUNCTION_ROUTES, re.M)
    assert function_limit, "function/routes.py no longer sets MAX_PDF_BYTES in MiB"
    assert stated(r"up to (\d+) MiB") == [int(function_limit.group(1))]
    assert stated(r"accepts up to (\d+) MiB", HOW_IT_WORKS) == [int(function_limit.group(1))]
    flow_limits = stated(r"files under (\d+) MiB") + stated(r"PDFs under (\d+) MiB", HOW_IT_WORKS) + stated(r"file of (\d+) MiB or larger", HOW_IT_WORKS)
    for mib in flow_limits:
        assert flowlib.DOWNLOAD_LIMIT_BASE64 == mib * 1024 * 1024 * 4 // 3


def test_the_status_list_is_the_schemas(schema: dict[str, Any]) -> None:
    contract = next(table for table in schema["tables"] if table["name"] == "vz_contract")
    options = next(column for column in contract["columns"] if column["name"] == "vz_status")["options"]
    listed = re.search(r"The contract status moves ([^']+)\.'", ARCHITECTURE)
    assert listed, "architecture.ts no longer lists the contract statuses"
    assert re.split(r",\s+(?:or\s+)?", listed.group(1)) == options


# ---- the standalone page ------------------------------------------------------------------------------------------

@pytest.fixture(scope="module")
def page() -> str:
    assert PAGE.is_file(), f"docs/architecture-3d.html is missing. {BUILD_COMMAND}"
    return PAGE.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def build_info(page: str) -> dict[str, Any]:
    block = re.search(r'<script type="application/json" id="build-info">\n(.*?)\n</script>', page, re.S)
    assert block, "the page has no build-info block, so nothing says what it was built from"
    return json.loads(block.group(1))


def file_hash(path: Path) -> str:
    """The same hash the build writes: SHA-256 of the file with line endings normalized, so every checkout agrees."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def test_the_page_was_built_from_the_sources_as_they_are_now(build_info: dict[str, Any]) -> None:
    changed = [path for path, recorded in build_info["builtFrom"].items()
               if not (APP / path).is_file() or file_hash(APP / path) != recorded]
    assert not changed, f"docs/architecture-3d.html is stale: {', '.join(changed)} changed since it was built. {BUILD_COMMAND}"


def test_the_page_was_built_from_the_diagram_and_its_scene(build_info: dict[str, Any]) -> None:
    built = set(build_info["builtFrom"])
    for path in ("src/about/architecture.ts", "src/about/scene/engine.ts", "src/standalone/StandalonePage.tsx", "standalone.html"):
        assert path in built, f"{path} is not among the sources the page records"


def test_the_page_was_built_with_the_libraries_the_lockfile_pins(build_info: dict[str, Any]) -> None:
    lock = json.loads((APP / "package-lock.json").read_text(encoding="utf-8"))["packages"]
    for name, version in build_info["packages"].items():
        assert lock[f"node_modules/{name}"]["version"] == version, f"{name} changed since the page was built. {BUILD_COMMAND}"


def test_the_page_is_one_file_with_nothing_to_fetch(page: str) -> None:
    # The app's code is escaped so that it cannot end its own element early: only the real closing tags remain.
    assert page.count("</script>") == 2  # the app, and the build info
    assert page.count("</style>") == 1
    markup = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", "", page, flags=re.S)
    assert "<script" not in markup and "<style" not in markup
    fetched = [url for url in re.findall(r"""\b(?:src|href)\s*=\s*["']([^"']*)["']""", markup) if not url.startswith("data:")]
    assert fetched == []
    styles = re.search(r"<style>(.*?)</style>", page, re.S).group(1)  # type: ignore[union-attr]
    assert not re.search(r"@import|url\(\s*[\"']?(?!data:|#)", styles)
    assert "__VITE_" not in page, "a Vite build marker was left in the page"


def test_the_page_names_no_host_of_a_real_environment(page: str) -> None:
    hosts = re.compile(r"\.(dynamics|sharepoint|onmicrosoft)\.com|\.azurewebsites\.net|\.(cognitiveservices|openai|services\.ai)\.azure\.com", re.I)
    assert not hosts.search(page)
